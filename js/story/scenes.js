/* Fixed story text: the opening scene and the three endings. */
import { END, MAX_HINTS } from "../state.js";
import { fmt } from "../util.js";

export const OPENING_NARRATION = "01:00. Трајковски седи спроти тебе. Рацете му се на масата.";
export const OPENING_LINE = "[Погледнува кон часовникот на ѕидот, па кон тебе.] Ајде, инспекторе. Прашувај. Имам цела ноќ.";
/* the opening line as a raw assistant turn, in the RULES output format */
export const OPENING_TURN = OPENING_LINE + '\n###\n{"resistance": 85, "revealed": [], "lawyer": false, "mood": "презрив"}';

/* outcome: "win" | "lawyer" | "time"; at: minute the interrogation ended. body paragraphs are separated by blank lines. */
export function ending(outcome, at, hintsLeft) {
  if (outcome === "win") {
    const left = END - at, used = MAX_HINTS - hintsLeft;
    return {
      stamp: "Решено", title: "Сара е жива",
      body: `${fmt(Math.min(at + 20, 359))}. Специјалната единица ја крши вратата на котларницата во подрумот на „Резиденција Вардар“. Цеко е совладан без истрел. Сара Ристевска е врзана и исплашена, но жива.

Утрото Бранко Мицевски е приведен во својата вила на Водно. Горан Трајковски потпишува изјава како соработник на правдата.

Илиевски ти ја става раката на рамо: „Добра работа, Викторе. Оди спиј малку.“`,
      rank: left >= 90 && used <= 1 ? "Оценка од Илиевски: легенда на одделот." : left >= 30 ? "Оценка од Илиевски: вистински инспектор." : "Оценка од Илиевски: за влакно, Викторе."
    };
  }
  if (outcome === "lawyer") return {
    stamp: "Прекинато", title: "Бара адвокат", rank: "",
    body: `Трајковски ги крстосува рацете на градите. „Без адвокат не зборувам повеќе.“

Распитот е прекинат. Додека се чека адвокатот, стрелките на часовникот се движат кон шест.

Подоцна Илиевски ќе ти каже само: „Ти реков, Викторе. Со закана не се отвора човек.“`
  };
  return {
    stamp: "Отворено", title: "Зората стигна прва", rank: "",
    body: `06:00. Во кесата со докази ѕвони телефонот на Трајковски. Никој не се јавува. Трајковски ја спушта главата на масата и дури тогаш проговорува.

Кога екипите стигнуваат до котларницата во подрумот на „Резиденција Вардар“ во Кисела Вода, затекнуваат само отворена врата и скинато јаже. Од Цеко и од Сара нема ни трага.

Случајот останува отворен.`
  };
}
